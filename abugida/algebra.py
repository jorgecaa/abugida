"""The algebra A = {0, 0+, 0−, 1, 1+, 1−} and its operations.

See SPEC.md §1 and §1.5. In short: A ≅ B × F₃, the product of the boolean
semiring (base = voicing, with OR and AND) and the field of three elements
(modifier = aspiration/nasality). `compose` (⊗) is the semiring's SUM;
`mult` (⊙) is its multiplication. A true ring is impossible under the given
axioms — `test_algebra.py::TestNoRing` documents why.
"""

from __future__ import annotations

from typing import NamedTuple

# Modifier: elements of Z₃.
EPSILON, PLUS, MINUS = 0, 1, 2

_MOD_SUFFIX = {EPSILON: "", PLUS: "+", MINUS: "−"}
# Accept the ASCII hyphen as well as the Unicode minus sign when parsing.
_SUFFIX_MOD = {"": EPSILON, "+": PLUS, "−": MINUS, "-": MINUS}


class A(NamedTuple):
    """An element of the algebra: base ∈ {0,1} × modifier ∈ Z₃."""

    base: int
    mod: int

    def __str__(self) -> str:
        return f"{self.base}{_MOD_SUFFIX[self.mod]}"

    @classmethod
    def parse(cls, s: str) -> "A":
        s = s.strip()
        if not s or s[0] not in "01":
            raise ValueError(f"not a recognised element of A: {s!r}")
        suffix = s[1:]
        if suffix not in _SUFFIX_MOD:
            raise ValueError(f"unrecognised modifier: {s!r}")
        return cls(int(s[0]), _SUFFIX_MOD[suffix])


def compose(x: A, y: A) -> A:
    """⊗ — the semiring's SUM: accumulation of features.

    Base by maximum (boolean OR: voicing absorbs and cannot be undone),
    modifier by addition in F₃ (aspiration and nasality cancel each other).
    """
    return A(max(x.base, y.base), (x.mod + y.mod) % 3)


# --- EXPERIMENTAL: the XOR variant of the base ----------------------------
# Not used by anything above `algebra`. Kept because "why isn't the base
# XOR?" is the first question the table raises, and a runnable answer beats
# a paragraph.


def compose_xor(x: A, y: A) -> A:
    """⊗ with the base as Z₂ (XOR) instead of the OR semilattice. EXPERIMENTAL.

    This is NOT the project's ⊗ and must not be substituted for `compose`:
    it contradicts the second given axiom. `1+ ⊗ 1− = 1` is data — a voiced
    aspirate composed with a nasal is voiced — and XOR returns `0`, a
    voiceless one. Every derivation in SPEC §1 downstream of that axiom goes
    with it.

    What it gives instead is worth knowing, because it is clean: with both
    axes groups, A becomes **Z₂ × Z₃ ≅ Z₆**, cyclic, generated by `1+` (the
    semiring's ONE), which walks 1+ → 0− → 1 → 0+ → 1− → 0. Everything is
    invertible; the orders are 2 for `1`, 3 for the voiceless modifiers and 6
    for `1+` and `1−`. Verified in `test_algebra.py::TestXorVariant`.

    It goes further than that, and this is the point of keeping it runnable.
    `⊙` still distributes over it, `0` still absorbs and `1+` is still
    neutral — so the XOR variant is a commutative RING with unit, and by the
    Chinese remainder theorem F₂ × F₃ ≅ **Z/6Z** exactly: the map sending
    `1+ ↦ 1` carries both operations at once (0↦0, 1+↦1, 0−↦2, 1↦3, 0+↦4,
    1−↦5). §1.5 opens by proving no ring is possible with ⊗; the honest
    statement is that the ring IS reachable, and the price is the axiom.

    That price is the whole argument:

    - voicing becomes REVERSIBLE (1 ⊗ 1 = 0), "devoicing by composition",
      which Pāli does not do. Being unable to subtract is the algebraic form
      of "accumulated voicing cannot be taken back" — §1.5 says a semiring is
      a ring without subtraction, and here is the subtraction it declines;
    - the paraconsistent reading of §2 collapses. There, the units are the
      voiceless values and the absorbing ideal is the voiced ones, so the
      explosive element is VOICING and the contradiction `0−` is a harmless,
      invertible unit. In Z/6Z everything is a unit of the additive group,
      nothing absorbs under ⊗, and the observation has no content left.

    Read it as the counterfactual that prices the axiom: one datum
    (`1+ ⊗ 1− = 1`) is what stands between this algebra and plain modular
    arithmetic on six elements.
    """
    return A((x.base + y.base) % 2, (x.mod + y.mod) % 3)


#: Bottom and top of that lattice: the plain voiceless stop and the nasal.
LATTICE_BOTTOM = A(0, EPSILON)
LATTICE_TOP = A(1, MINUS)


def or_(x: A, y: A) -> A:
    """Lattice JOIN on A, componentwise maximum. EXPERIMENTAL.

    Not ⊗. It agrees with ⊗ on the base (both are OR there) and differs on
    the modifier, where ⊗ adds in F₃ and this takes a maximum.

    THE ORDER IS A CHOICE, and the integer encoding hides it: the base
    {0 < 1} is forced, but the modifier is read as the chain ε < + < −, and
    Z₃ is cyclic with no intrinsic order. This particular chain is picked so
    that `not_` comes out as the order-reversing involution. It does not
    privilege the conclusion — `sum_` fails to reproduce either ⊗ or
    `compose_xor` under ALL TWELVE assignments of ranks to the two axes
    (3! × 2!), which is checked in `test_algebra.py`.
    """
    return A(max(x.base, y.base), max(x.mod, y.mod))


def and_(x: A, y: A) -> A:
    """Lattice MEET on A, componentwise minimum. EXPERIMENTAL.

    Not ⊙. It agrees with ⊙ on the base (both are AND) and differs on the
    modifier, where ⊙ multiplies in F₃ and this takes a minimum.
    """
    return A(min(x.base, y.base), min(x.mod, y.mod))


def not_(x: A) -> A:
    """De Morgan complement: reverse both coordinates. EXPERIMENTAL.

    base 1−b, modifier 2−m — so ε ↔ −, and + is its own image.
    """
    return A(1 - x.base, 2 - x.mod)


def sum_(x: A, y: A) -> A:
    """Symmetric difference built from the lattice: (a∧¬b) ∨ (¬a∧b).
    EXPERIMENTAL — and the point of the whole experimental block.

    In a BOOLEAN algebra this construction is XOR, so if A were boolean it
    would reproduce `compose_xor` and, through it, the ring Z/6Z. It does
    not, and the way it fails is the finding.

    MEASURED (`test_algebra.py::TestLatticeOps`):

    - `or_`/`and_`/`not_` do form a distributive **De Morgan algebra**:
      the complement is involutive and De Morgan's laws hold, over all pairs.
    - It is **not boolean**. Exactly `0+` and `1+` — the aspirates, the
      middle of the modifier chain — have no complement. The MODIFIER `+` is
      fixed by 2−m (the element is not: `not_(0+) = 1+`), so the modifier
      coordinate of `x ∧ ¬x` stays at `+` and never reaches the bottom's ε,
      however the base cancels. A three-value
      chain with an order-reversing involution is Kleene's, not Boole's,
      which is the shape §2 gestures at when it says a paraconsistent
      *consequence* would need an information order distinct from ⊗.
    - Hence `sum_` is NOT `compose_xor`: they agree on exactly 20 of the 36
      pairs, and the rule is sharp — **they agree iff at least one operand is
      unmarked** (modifier ε). With both marked, the lattice cannot cancel.
    - `sum_` is associative and commutative with `0` neutral, but it is NOT a
      group: `sum_(0+, 0+) = 0+`, so the aspirate has no inverse.

    The one-line reading: a lattice cannot express cyclicity. `+ ⊗ + = −`
    — aspiration composed with itself giving nasality — is genuinely
    arithmetic in Z₃, and no join/meet/complement over any of the twelve
    product orderings of these six elements reconstructs it (exhaustive, see
    the test). The modifier being a FIELD rather than a boolean algebra is
    load-bearing, and this is the demonstration.
    """
    return or_(and_(x, not_(y)), and_(not_(x), y))


def mult(x: A, y: A) -> A:
    """⊙ — the semiring's MULTIPLICATION: coincidence of features.

    Base by minimum (boolean AND: voiced only if both are), modifier by
    product in F₃ (the unmarked value, ε = 0, absorbs the mark). It
    distributes over ⊗ because AND distributes over OR and F₃ is a field.
    """
    return A(min(x.base, y.base), (x.mod * y.mod) % 3)


# The six elements, in the order of the table in SPEC.md.
VOICELESS = A(0, EPSILON)
VOICELESS_ASPIRATED = A(0, PLUS)
NIGGAHITA = A(0, MINUS)
VOICED = A(1, EPSILON)
VOICED_ASPIRATED = A(1, PLUS)
NASAL = A(1, MINUS)

ELEMENTS = (
    VOICELESS,
    VOICELESS_ASPIRATED,
    NIGGAHITA,
    VOICED,
    VOICED_ASPIRATED,
    NASAL,
)

#: ZERO of the semiring: neutral for ⊗ and absorbing for ⊙. The plain
#: voiceless stop.
ZERO = VOICELESS
IDENTITY = ZERO  # historical alias: plain "identity" = the additive one

#: ONE of the semiring: neutral for ⊙. The voiced aspirate (gh, jh, ḍh, dh, bh).
ONE = VOICED_ASPIRATED


def is_unit(x: A) -> bool:
    """Is x invertible with respect to ⊗ (the sum)?

    Exactly the voiceless values are. That `0−` (the niggahīta, contradictory
    in classical features) is a unit is the paraconsistent point: the
    contradiction is reversible and does not absorb. See SPEC.md §2.
    """
    return x.base == 0


def inverse(x: A) -> A:
    """Inverse of x with respect to ⊗. Exists only for voiceless values."""
    if not is_unit(x):
        raise ValueError(f"{x} is not invertible: voicing absorbs")
    return A(0, (-x.mod) % 3)


def is_unit_mult(x: A) -> bool:
    """Is x invertible with respect to ⊙ (the multiplication)?

    Exactly {1+, 1−} ≅ Z₂ — the mirror image of the additive units (the
    voiceless values, ≅ Z₃). `1−` is an involution: 1− ⊙ 1− = 1+, because
    2 · 2 ≡ 1 in F₃. Nasal times nasal gives aspirate.
    """
    return x.base == 1 and x.mod != EPSILON


def inverse_mult(x: A) -> A:
    """Inverse of x with respect to ⊙. Exists only for 1+ and 1−."""
    if not is_unit_mult(x):
        raise ValueError(f"{x} is not invertible with respect to ⊙")
    # In F₃*, every element is its own inverse: 1·1 = 1 and 2·2 = 1.
    return x
