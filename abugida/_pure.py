"""The pure-Python metric: the reference implementation, and the oracle.

This is the original implementation of the distance, kept runnable on
purpose. The package ships a C core (`csrc/`) and `abugida.distance`
delegates to it; this module is what the C core is checked against.

Two things make it worth carrying rather than deleting:

- **It is the ORACLE.** `tests/test_c_parity.py` compares the C core with
  this module over the whole alphabet, over the token vocabulary, and over a
  fixed-seed sample of words, and requires exact agreement — not approximate.
  A second implementation is a liability only when it can drift; here
  drift is what the test detects.
- **It derives the constants the C tables are generated FROM.**
  `tools/generate_c_tables.py` imports `INDEL_WEIGHT`, `_GEMINATE_BASES`,
  `EPENTHETIC` and `cost` from this file and `eval/` scripts import them
  through `abugida.distance`. `INDEL_WEIGHT` in particular is computed here
  at import time from the embeddings (the extremal epenthetic weight the
  triangle inequality permits), so there is exactly one derivation of it.

It is also the fallback: if the extension is absent, `abugida.distance`
re-exports these functions and the package behaves exactly as it did before
the C core existed. The docstrings below are the theory, and they describe
the metric in both implementations — see SPEC.md for the derivation.

See SPEC.md §14. Three layers:

1. `algebraic_cost(x, y)` over A — the word metric of the group generated by
   ⊗: changing the base (voicing) is one move, changing the modifier is
   another (just ONE, whichever it is: since + ⊗ + = −, aspirating and
   nasalising are both a single application). d_A ∈ {0, 1, 2}.

2. `cost(g1, g2)` between phonemes — the truncated ANGULAR distance between
   embeddings weighted by ρ* (the balance weight of §4):
   min(1, arccos(cos)/(π/2)). The angular distance is a metric (spherical
   geodesic) and truncation preserves that. Because the embedding is the
   homomorphic image of ⊗, this geometry IS the algebra; and it also sees
   what A does not reach: places (multi-hot lattice), vowel length, etc.

3. `distance(w1, w2)` between words — weighted edit distance (dynamic
   programming) over each word's ONE segmentation into tokens and heavy
   units (geminates and homorganic nasal+stop clusters, `_segment`):
   substitution = phonological cost ∈ [0,1], insertion/deletion = 1, the
   epenthetic weight, or a unit's derived indel. With a metric cost and
   indels that satisfy the triangle against it, edit distance is a METRIC
   over the unit sequences (Wagner–Fischer), and a word has one sequence.
   It usually stays under `levenshtein`, which counts letters, but a unit
   against two different letters can exceed it (tatra~tattha 1.470 against
   one Levenshtein edit).

`levenshtein(w1, w2)` (also over tokens, so both use the same segmentation)
is the baseline: it treats every change as equally grave, whereas the
phonological distance grades them. All of kata~gata (0.470), citta~cinta
(0.631) and kata~pata (0.889) are one Levenshtein edit; only the second
measure knows that voicing a stop is a near-miss and swapping the two ends
of the tract is not.

The example NOT to use here is saṅgha~saṃgha: raw, it is 0.740, next to
dhamma~dharma's 0.746 — this metric alone does not separate them. What
separates them is the recommended pipeline, phonology first and metric
second: `sandhi.assimilate_word` rewrites saṃgha to saṅgha, and the pair
then measures 0.0 while dhamma~dharma stays at 0.746. Niggahīta assimilation
is a normalisation, like contraction (§9.1), and it is deliberately not an
edit operation.

`distance` is a true metric — identity, symmetry and the triangle
inequality — over all words, the empty one included. The three token-level
conditions it rests on are verified exhaustively (`cost`'s triangle over
every triple of tokens, letters, heavy units and Sanskrit phonemes alike,
and the two cost/indel conditions over every pair), and the word-level
inequality is checked on triples in tests. It did not hold before the heavy
units: alignment transitions let each comparison read a geminate as one
long consonant or two letters, and `d("makka","saṅgha")` was 2.262 against
2.065 through `magga` (SPEC §14, `eval/triangle_geminates.py`).
"""

from __future__ import annotations

import math
from functools import lru_cache
from typing import List

from .algebra import A
from .embed import DIM, NEUTRAL_MODIFIER_WEIGHT, cosine, embed
from .iast import tokenize
from .embed import LENGTH as _LENGTH_DIM
from .phonology import BY_GRAPHEME, FOREIGN, INVENTORY, VOWELS


def algebraic_cost(x: A, y: A) -> int:
    """Generator moves of ⊗ between two values of A: 0, 1 or 2."""
    return int(x.base != y.base) + int(x.mod != y.mod)


@lru_cache(maxsize=None)
def cost(g1: str, g2: str) -> float:
    """Cost of substituting grapheme g1 with g2, in [0, 1] — and a METRIC.

    Truncated angular distance: min(1, θ/(π/2)) with θ = arccos of the cosine
    weighted by ρ*. The angular distance is the sphere's geodesic (spherical
    triangle inequality ⇒ metric), and truncating at 1 preserves that
    (min(1, d) of a metric is a metric). Orthogonal or worse = 1:
    substituting never beats delete+insert between unrelated sounds.

    Since arccos is monotone, it inherits everything structural from the
    cosine: the balance k↔kh = k↔g (ρ*, §4) and monotonicity with
    `algebraic_cost`.

    LINEAR, AND DERIVED. Read the edit distance as a NOISY CHANNEL — the
    standard reading, and the reason costs SUM at all: a word is corrupted by
    independent operations and the cost of one is −log P(operation), so a
    path's cost is the corruption's negative log-likelihood. That fixes the
    transformation rather than leaving it to taste: cost must be ∝ −log P,
    so exponential decay of confusability implies a LINEAR cost and power-law
    decay implies a logarithmic one.

    Measured (`eval/noisy_channel.py`): over the operating range the decay is
    exponential and linear wins — R² 0.974 against log's 0.932 at d ≤ 1.5,
    and identity wins at every cut through 2.5. Log overtakes it only once
    the tail beyond d ≈ 3 is included, where P ≈ 0.0001 and no usable
    threshold reaches (θ=1.5 already costs 10.6 candidates per lemma).

    So a concave f (log, sqrt) is not merely unprofitable here — it is wrong
    for the decay the data shows, and its apparent advantage came from
    fitting a tail with no signal. It was nonetheless implemented and
    measured before this was known: admissible (concave with f(0)=0 is
    subadditive, which carries the triangle inequality through) but neutral
    at equal candidate volume, and it shifted the scale 4.3% towards
    Levenshtein. TODO.md has those numbers; do not re-measure either half.

    The caveat that bounds the claim: this derives the right transformation
    OF THIS GEOMETRY. It does not validate the geometry, which rests on §4.

    OPAQUE tokens (non-Pāli characters admitted by lenient tokenisation)
    cost 0 against themselves and 1 against everything else. The extension
    preserves the metric: {0, 1} costs against values in [0, 1] cannot
    violate the triangle inequality (tested exhaustively with opaque tokens
    included). A typo has no phonology, so 1 — indistinguishable from any
    unrelated sound — is the honest cost.

    HEAVY UNITS (geminates and homorganic nasal+stop clusters, see `_UNITS`)
    are priced by their halves: a unit is (first half, second half, weight),
    a single token X is (X, X, light), and the cost is the largest of the
    three coordinate costs — the angular cost between first halves, between
    second halves, and the difference of weights. The maximum of metrics on
    a product is a metric, so this extends the metric to the units; and it
    is what makes a geminate count once (kk~gg = k~g), a cluster differ from
    a geminate by the half that differs (tt~nt = t~n), and a change inside a
    cluster cost what it costs alone (nt~nd = t~d). Between single tokens it
    is the angular cost unchanged.
    """
    if g1 == g2:
        return 0.0
    return _by_halves(g1, g2, _angular, _weight)


@lru_cache(maxsize=None)
def _angular(g1: str, g2: str) -> float:
    """The truncated angular distance between two SINGLE tokens (see `cost`)."""
    if g1 == g2:
        return 0.0
    v1 = _vector(g1)
    v2 = _vector(g2)
    if v1 is None or v2 is None:
        return 1.0
    c = cosine(v1, v2, NEUTRAL_MODIFIER_WEIGHT)
    theta = math.acos(max(-1.0, min(1.0, c)))
    return min(1.0, theta / (math.pi / 2.0))


def _by_halves(g1: str, g2: str, single, weight) -> float:
    """Compose a cost over single tokens into one over heavy units too: the
    max of the first-half cost, the second-half cost and the weight gap."""
    h1 = _UNITS.get(g1)
    h2 = _UNITS.get(g2)
    if h1 is None and h2 is None:
        return single(g1, g2)
    a1, b1 = h1 or (g1, g1)
    a2, b2 = h2 or (g2, g2)
    return max(single(a1, a2), single(b1, b2),
               abs(weight(g1) - weight(g2)))


# --- heavy units: geminates and nasal+stop clusters, one segmentation ----
# Pāli geminates are LONG consonants — the same phonological parameter as
# vowel length, and the metrical tradition treats both alike (they "make
# position"); so does a homorganic nasal+stop cluster (nt, ṅk, mb…), the
# other heavy coda the phonotactics knows (SPEC §13, family c). Each is ONE
# token of the word, a heavy unit: the DP segments every word once, before
# measuring, and compares unit sequences with plain substitutions and indels.
#
# Why one segmentation, and not alignment transitions. The distance used to
# admit 2:1 / 1:2 / 2:2 transitions that let EACH comparison decide whether
# a doubled pair was one long consonant or two letters. Composition then
# broke: a middle word read as a unit in one leg and as letters in the other
# made the detour cheaper than the direct path (makka -> magga -> saṅgha,
# 2.262 > 2.065; 86 violations in 26,400 triples). Every repair that kept
# per-comparison segmentation failed (`eval/triangle_geminates.py`). With one
# segmentation per word, a metric cost over the tokens and indels that
# satisfy the triangle against it, the edit distance is a metric by the
# classical argument: every operation has an inverse of equal cost and
# alignments compose. The geminate-vs-cluster pairs that an earlier
# collapse-based design lost (citta/cinta) are kept by making the cluster a
# unit too, priced by its halves (`cost`).

_VOWEL_GRAPHEMES = frozenset(p.grapheme for p in VOWELS)
_GEMINATE_BASES = {}  # internal token → base grapheme
for _g, _p in BY_GRAPHEME.items():
    if _g in _VOWEL_GRAPHEMES or _g == "ṃ":
        continue
    _GEMINATE_BASES[_g + _g] = _g  # plain geminate: tt, kk, ss, yy…
    if _p.value is not None and _p.value.mod == 0:
        for _h, _q in BY_GRAPHEME.items():
            if (_q.places == _p.places and _q.value is not None
                    and _q.value.base == _p.value.base
                    and _q.value.mod == 1):
                _GEMINATE_BASES[_g + _h] = _h  # aspirated: tth → long th


_NASALS = frozenset(
    g for g, p in BY_GRAPHEME.items()
    if p.value is not None and p.value.mod == 2)  # the modifier −: nasality
_STOPS = frozenset(
    g for g, p in BY_GRAPHEME.items()
    if p.value is not None and p.value.mod in (0, 1))

#: Heavy unit token -> (first half, second half). The geminates of
#: `_GEMINATE_BASES` (tt -> (t, t), tth -> (t, th)) and every homorganic
#: nasal+stop cluster (nt -> (n, t), ṅkh -> (ṅ, kh)): a nasal and a stop
#: sharing a place, the non-empty meet of the lattice that `assimilate` and
#: the phonotactics use. The niggahīta carries all five places, so the same
#: rule makes ṃ + any stop a unit (saṃgha's ṃgh): before a stop it IS the
#: cluster's nasal half, written unassimilated, and saṃgha ~ saṅgha differs
#: only in that half (ṃ~ṅ).
_UNITS = {g: (g[:len(g) - len(b)], b) for g, b in _GEMINATE_BASES.items()}
for _n in sorted(_NASALS):
    for _s in sorted(_STOPS):
        if BY_GRAPHEME[_n].places & BY_GRAPHEME[_s].places:
            _UNITS[_n + _s] = (_n, _s)


def _long_vector(g: str):
    """The second half's embedding with the LENGTH dimension set: the
    geometry's own picture of a heavy consonant."""
    v = list(embed(BY_GRAPHEME[_UNITS[g][1]]))
    v[_LENGTH_DIM] = 1.0
    return v


@lru_cache(maxsize=None)
def _weight(g: str) -> float:
    """The weight coordinate of a token: 0 for a single token; for a heavy
    unit, the angular cost between its second half and that half made long —
    exactly what degemination cost before units, consonant by consonant
    (0.470 for t, 0.377 for d, 0.295 for l). Derived from the LENGTH
    dimension the embedding already has; no new number."""
    if g not in _UNITS:
        return 0.0
    v = _long_vector(g)
    c = cosine(v, embed(BY_GRAPHEME[_UNITS[g][1]]), NEUTRAL_MODIFIER_WEIGHT)
    return min(1.0, math.acos(max(-1.0, min(1.0, c))) / (math.pi / 2.0))


def _segment(tokens: List[str]) -> List[str]:
    """The word's one segmentation: adjacent tokens forming a heavy unit
    become that unit, left to right; everything else stays as it is.

    Greedy is not a choice among readings: Pāli phonotactics allows at most
    two consonants between vowels except before a liquid (SPEC §13), so two
    candidate units never overlap in a word the inventory can spell."""
    out: List[str] = []
    i = 0
    n = len(tokens)
    while i < n:
        if i + 1 < n:
            pair = tokens[i] + tokens[i + 1]
            if pair in _UNITS and _UNITS[pair] == (tokens[i], tokens[i + 1]):
                out.append(pair)
                i += 2
                continue
        out.append(tokens[i])
        i += 1
    return out


#: The EPENTHETIC class: graphemes whose insertion/deletion is attested as
#: ordinary transmission variation in Geiger's grammar — svarabhakti vowels
#: (sve/suve, sotthi/suvatthi), prothetic glides (uṭṭhita/vuṭṭhita),
#: initial-vowel aphaeresis (idāni/dāni) and final niggahīta loss
#: (sakiṃ/saki). Everything else keeps the full indel cost of 1.
EPENTHETIC = frozenset("aāiīuūeo") | frozenset(["y", "v", "ṃ"])

#: Their indel weight is DERIVED, not tuned: the cheapest value the metric
#: allows. On Σ ∪ {ε} the triangle inequality forces, for every full-price
#: symbol c and epenthetic g,  indel(c) ≤ cost(c, g) + indel(g), i.e.
#: indel(g) ≥ 1 − min cost(class, non-class); and for g1, g2 in the class,
#: cost(g1, g2) ≤ indel(g1) + indel(g2), i.e. indel ≥ max in-class cost / 2.
#: The weight is the larger of the two lower bounds — the extremal solution,
#: verified exhaustively in tests.
INDEL_WEIGHT: float  # assigned at the end of the module


def _indel(g: str) -> float:
    """Insertion/deletion cost of a token. A heavy unit's is derived: the
    cheapest route through a single token (`_UNIT_INDEL`, end of module)."""
    if g in _UNITS:
        return _UNIT_INDEL[g]
    return INDEL_WEIGHT if g in EPENTHETIC else 1.0


def _vector(g: str):
    """Embedding for a grapheme, a foreign phoneme, or a heavy unit (its
    second half made long — what `_weight` measures; `cost` itself prices
    units by their halves and never compares these vectors)."""
    if g in _UNITS:
        return _long_vector(g)
    p = BY_GRAPHEME.get(g) or FOREIGN.get(g)
    return None if p is None else embed(p)


def _edit(t1: List[str], t2: List[str], substitution, indel=_indel,
          geminates: bool = True) -> float:
    """Edit distance with the given substitution and indel costs (DP).

    With `geminates` (the default) each word is first segmented into heavy
    units (`_segment`), so a geminate or a nasal+stop cluster is ONE token of
    the comparison; without it the tokens are compared as they come, which
    is what `levenshtein` does. The keyword keeps its old name because the
    unit vocabulary began with the geminates."""
    if geminates:
        t1, t2 = _segment(t1), _segment(t2)
    n, m = len(t1), len(t2)
    ind2 = [indel(g) for g in t2]
    prev = [0.0] * (m + 1)
    for j in range(1, m + 1):
        prev[j] = prev[j - 1] + ind2[j - 1]
    for i in range(1, n + 1):
        a = t1[i - 1]
        da = indel(a)
        cur = [prev[0] + da] + [0.0] * m
        for j in range(1, m + 1):
            best = prev[j] + da  # delete
            ins = cur[j - 1] + ind2[j - 1]
            if ins < best:
                best = ins
            sub = prev[j - 1] + substitution(a, t2[j - 1])
            if sub < best:
                best = sub
            cur[j] = best
        prev = cur
    return prev[m]


def distance(w1: str, w2: str, lenient: bool = False) -> float:
    """Phonological distance between two IAST words.

    With `lenient=True`, characters outside the Pāli alphabet become opaque
    tokens (cost 1 against everything) instead of raising: the comparison
    degrades gracefully and the intact remainder of the word still
    discriminates. Report the absorbed characters with `iast.diagnose`.
    """
    return _edit(tokenize(w1, lenient), tokenize(w2, lenient), cost)


def levenshtein(w1: str, w2: str, lenient: bool = False) -> int:
    """Classic Levenshtein over the SAME tokens (kh = one letter).

    The baseline: same segmentation, but every change weighs 1.
    """
    flat = lambda a, b: 0.0 if a == b else 1.0
    return int(_edit(tokenize(w1, lenient), tokenize(w2, lenient), flat,
                     indel=lambda g: 1.0, geminates=False))


def neighbors(word: str, candidates, k: int = 5, lenient: bool = False) -> List[tuple]:
    """The k phonologically nearest candidates, with both measures."""
    rows = [
        (distance(word, c, lenient), levenshtein(word, c, lenient), c)
        for c in candidates
        if c != word
    ]
    return sorted(rows)[:k]


def alignment(w1: str, w2: str, lenient: bool = False) -> List[tuple]:
    """The optimal edit script between two words — the information the
    scalar `distance` aggregates away.

    Returns a list of operations (op, from_grapheme, to_grapheme, cost) with
    op ∈ {"keep", "sub", "del", "ins"}; "keep" carries cost 0.0, "del"/"ins"
    carry 1.0 and None on the missing side. The costs sum exactly to
    `distance(w1, w2)` (tested), so nothing is lost between the two views:
    `distance` answers "how far", `alignment` answers "along which path".
    """
    t1 = _segment(tokenize(w1, lenient))
    t2 = _segment(tokenize(w2, lenient))
    n, m = len(t1), len(t2)
    d = [[0.0] * (m + 1) for _ in range(n + 1)]
    for i in range(1, n + 1):
        d[i][0] = d[i - 1][0] + _indel(t1[i - 1])
    for j in range(1, m + 1):
        d[0][j] = d[0][j - 1] + _indel(t2[j - 1])
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            d[i][j] = min(
                d[i - 1][j] + _indel(t1[i - 1]),
                d[i][j - 1] + _indel(t2[j - 1]),
                d[i - 1][j - 1] + cost(t1[i - 1], t2[j - 1]),
            )
    ops: List[tuple] = []
    i, j = n, m
    while i or j:
        if (
            i
            and j
            and abs(d[i][j] - (d[i - 1][j - 1] + cost(t1[i - 1], t2[j - 1])))
            < 1e-12
        ):
            a, b = t1[i - 1], t2[j - 1]
            ops.append(("keep" if a == b else "sub", a, b, cost(a, b)))
            i, j = i - 1, j - 1
        elif i and abs(d[i][j] - (d[i - 1][j] + _indel(t1[i - 1]))) < 1e-12:
            ops.append(("del", t1[i - 1], None, _indel(t1[i - 1])))
            i -= 1
        else:
            ops.append(("ins", None, t2[j - 1], _indel(t2[j - 1])))
            j -= 1
    return list(reversed(ops))


def _derived_indel_weight() -> float:
    """The extremal epenthetic indel weight (see EPENTHETIC/INDEL_WEIGHT).

    The universe includes the FOREIGN phonemes: they carry full indel price,
    so any of them lying phonologically close to an epenthetic grapheme
    (ś next to y) tightens the Lipschitz bound."""
    from .alphabet import ALPHABET

    letters = [p.grapheme for p in ALPHABET] + sorted(FOREIGN)
    in_class = [g for g in letters if g in EPENTHETIC]
    out_class = [g for g in letters if g not in EPENTHETIC]
    bound_lipschitz = 1.0 - min(
        cost(g, c) for g in in_class for c in out_class
    )
    bound_pairs = max(
        cost(g1, g2) for g1 in in_class for g2 in in_class
    ) / 2.0
    return max(bound_lipschitz, bound_pairs)


INDEL_WEIGHT = _derived_indel_weight()

#: A heavy unit's indel, DERIVED: the cheapest route through a single token
#: (change the unit into it, then delete that) — the upper extremal value the
#: triangle inequality allows, since deleting the unit can never be dearer
#: than such a route. tt goes cheapest through v (0.700 + 0.627 = 1.327),
#: yy through y (its degemination 0.333 + 0.627 = 0.960) — against 2.0 for
#: deleting the two letters of tt one by one. The
#: Lipschitz and pair conditions against every other token follow from the
#: minimum and are verified exhaustively in tests.
def _derived_unit_indel() -> dict:
    from .alphabet import ALPHABET

    singles = [p.grapheme for p in ALPHABET] + sorted(FOREIGN)
    return {g: min(cost(g, x) + _indel(x) for x in singles) for g in _UNITS}


_UNIT_INDEL = _derived_unit_indel()

#: The costliest single attested-variation move: the MAXIMUM over the
#: elementary moves, not an alias of any one of them — that is what makes
#: "every cheaper move falls under it" true by construction rather than by
#: coincidence. The moves are an epenthetic indel, one move in the algebra
#: (k↔kh, equal to k↔g by the balance principle), degemination (tt↔t) and
#: vowel length (a↔ā).
#:
#: It currently EQUALS `INDEL_WEIGHT`, and was written as an alias of it for
#: that reason — but which move is dearest is a fact about the calibration,
#: not a definition. A trial re-warp of `cost` (concave, since reverted:
#: TODO.md) dropped the epenthetic indel BELOW a single algebra move, and the
#: alias silently stopped covering k↔kh: `variants` returned nothing for
#: kamma. The max is what the docstring always claimed; keeping it costs
#: nothing and the alias is known to be fragile. Do not collapse it back.
#:
#: Defined here, beside the constants it is the maximum of, because the C
#: tables carry it — and imported from `abugida.lexicon` by every caller that
#: has always got it from there.
ONE_MOVE = max(
    INDEL_WEIGHT,
    cost("k", "kh"),  # one move in the algebra
    cost("tt", "t"),  # degemination: consonant length
    cost("a", "ā"),  # vowel length
)


# --- EXPERIMENTAL: the componentwise weighted distance --------------------
# Not used by anything: `distance` and `cost` above are untouched. Kept
# runnable because "why an angle instead of a weighted sum of components?"
# is a reasonable question about §14, and the answer is measured, not
# asserted. See SPEC §4.


def _l1(g1: str, g2: str, weights: List[float]) -> float:
    v1, v2 = _vector(g1), _vector(g2)
    if v1 is None or v2 is None:
        return float("inf")
    return sum(abs(a - b) * w for a, b, w in zip(v1, v2, weights))


def _balanced_l1_weight() -> float:
    """The modifier weight for `weighted_cost`, by the SAME balance principle
    that fixes ρ* for the angular cost (§4): the unique ρ making
    weighted_cost(k,kh) == weighted_cost(k,g). Bisection, so it re-derives if
    the embedding layout changes. Comes out ≈ 0.4226, near the angular
    0.4580 — the principle transfers even though the geometry does not.
    """
    lo, hi = 1e-9, 10.0
    for _ in range(200):
        rho = (lo + hi) / 2.0
        w = [1.0] * DIM
        w[6] = w[7] = rho
        if _l1("k", "kh", w) > _l1("k", "g", w):
            hi = rho
        else:
            lo = rho
    return (lo + hi) / 2.0


L1_MODIFIER_WEIGHT = _balanced_l1_weight()

#: The per-dimension weights: 1.0 everywhere except the modifier plane,
#: which carries the balance weight. One weight, derived — not fourteen
#: free parameters, which is what "a system of weights" would otherwise
#: mean and what the project's discipline forbids.
L1_WEIGHTS = [1.0] * DIM
L1_WEIGHTS[6] = L1_WEIGHTS[7] = L1_MODIFIER_WEIGHT

#: Normaliser: the largest weighted L1 distance in the inventory, so that
#: `weighted_cost` lands in [0, 1] like `cost` and the two are comparable.
_L1_MAX = max(
    _l1(p.grapheme, q.grapheme, L1_WEIGHTS)
    for p in INVENTORY
    for q in INVENTORY
    if p.grapheme != q.grapheme
)


def weighted_cost(g1: str, g2: str) -> float:
    """Σᵢ wᵢ·|xᵢ − yᵢ| over the embedding, normalised to [0, 1]. EXPERIMENTAL.

    The natural alternative to `cost`'s truncated angular distance: instead
    of an angle between vectors, a weighted sum of componentwise differences.
    It IS a metric — a weighted L1 with non-negative weights always is, and
    the triangle inequality is verified in tests — and it takes the same
    calibration: `L1_MODIFIER_WEIGHT` is derived by the balance principle,
    exactly as ρ* is.

    NOTE the weights must be the SAME on both sides. The tempting general
    form Σᵢ |xᵢ·cᵢ − yᵢ·dᵢ| with c ≠ d is not a metric at all: it is
    asymmetric (d(k,g)=1.0 against d(g,k)=2.0 for one such choice) and loses
    identity (d(g,g) ≠ 0). Only c = d survives, and then it collapses to the
    form above.

    MEASURED, and it is why this is not `cost`:

    - Uncalibrated it breaks both structural properties — aspiration costs
      2.4× voicing (against the balance principle), and k↔gh (two algebra
      moves, 3.366) overtakes k↔p (a whole change of place, 2.414). Deriving
      the modifier weight repairs both, so that is not the objection.
    - Calibrated, it still scores **24–25 of 29** on the discrimination
      battery against the angular cost's **29**, with **4 ties** where the
      angular has none. The ties are the diagnosis: it prices `a↔ā`, `k↔kh`
      and `k↔g` identically at 0.128, where the angular separates them
      (0.333 and 0.470). An angle divides by the vectors' norms, so the same
      absolute displacement means more for a lightly specified segment than
      for a heavily specified one; an L1 sum cannot see that.
    - Its scale sits far lower against the indels. Normalising by the
      inventory's maximum puts a handful of pairs at 1.0 by construction,
      but only **0.4%** of letter pairs reach the cap against the angular
      cost's **22.8%**, and the median is 0.510 against 0.746. So
      delete+insert is almost never competitive and the DP loses, in
      practice, a degree of freedom the angular version keeps.

    So: a metric, calibratable by the same principle, and measurably worse.
    Kept as the runnable answer to "why an angle?".
    """
    if g1 == g2:
        return 0.0
    return _by_halves(g1, g2, _weighted_single, _weighted_weight)


def _weighted_single(g1: str, g2: str) -> float:
    if g1 == g2:
        return 0.0
    d = _l1(g1, g2, L1_WEIGHTS)
    return 1.0 if d == float("inf") else min(1.0, d / _L1_MAX)


def _weighted_weight(g: str) -> float:
    """`_weight` in this geometry: a unit's second half against itself long."""
    if g not in _UNITS:
        return 0.0
    second = _UNITS[g][1]
    return min(1.0, _l1(g, second, L1_WEIGHTS) / _L1_MAX)


def weighted_distance(w1: str, w2: str, lenient: bool = False) -> float:
    """`distance` with `weighted_cost` in place of `cost`. EXPERIMENTAL.

    Same DP, same heavy units, same epenthetic indels — only the
    substitution cost differs, so the comparison isolates the geometry.
    """
    return _edit(tokenize(w1, lenient), tokenize(w2, lenient), weighted_cost)
