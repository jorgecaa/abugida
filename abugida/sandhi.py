"""Word-level sandhi: the niggahīta, and vowel junction.

See SPEC.md §6. The glut of ṃ is resolved against what follows, within the
word (or within an already-joined compound). Following traditional grammar
(Kaccāyana: «vagge vaggantaṃ»):

- ṃ + stop → that series' nasal: saṃgha → saṅgha, saṃjāta → sañjāta.
  Mechanism: the meet of the place lattice — `assimilate` in phonology.py.
- ṃ + y → ññ: saṃyutta → saññutta. The palatal semivowel nasalises and
  geminates; this is not the plain meet (y is not a stop) but a rule of its
  own, attested as a variant in the canon (saṃyojana ~ saññojana).
- Otherwise (vowel, s, h, r, l, v, end of word): ṃ stays as it is — the
  unresolved glut, residual nasalisation (the glut/gap divergence of §2).

Assimilation before stops is optional in manuscript orthography (saṃgha and
saṅgha coexist); `assimilate_word` produces the canonical assimilated form.
"""

from __future__ import annotations

from typing import List, Optional

from .iast import normalize, tokenize
from .phonology import VOWELS, assimilate, phoneme

try:  # pragma: no cover - the branch taken depends on the build
    from . import _cabugida as _c
except ImportError:  # pragma: no cover
    _c = None


def assimilate_word(word: str) -> str:
    """Resolve every niggahīta in the word against what follows it.

    Returns normalised IAST (lowercase, NFC, editorial marks dropped).

    Runs on the C core when it is built: the rule is the same lattice meet,
    and the table the core consults is generated by calling
    `phonology.assimilate` once per grapheme, so the two agree by
    construction rather than by inspection.

    The input is normalised HERE, before the core sees it, and that is not a
    redundancy: the core's contract is to receive NFC-normalised lowercase
    IAST, so NFD input (a decomposed ṃ, the shape a macOS clipboard or a
    filename round trip produces) would tokenise as `s`, `a`, a combining dot
    and fail. `docs/comparator.md` promises normalisation is automatic; this
    is where that promise is kept for this function. `contract_word` below
    normalises for the same reason, and the pure-Python path always did.
    """
    word = normalize(word)
    if _c is not None:
        return _c.assimilate_word(word)
    tokens = tokenize(word)
    out: List[str] = []
    i = 0
    while i < len(tokens):
        t = tokens[i]
        if t != "ṃ" or i + 1 == len(tokens):
            out.append(t)
            i += 1
            continue
        following = tokens[i + 1]
        if following == "y":
            out.extend(["ñ", "ñ"])  # ṃ+y → ññ: nasalise and geminate
            i += 2
            continue
        # Before a stop the lattice meet picks that series' nasal; before
        # anything else `assimilate` returns ṃ untouched.
        out.append(assimilate(following).grapheme)
        i += 1
    return "".join(out)


# --- Contraction: the same join, inside the word ---------------------------

#: The contractions that pay for themselves, measured (eval/variant_curve.py):
#: `aya` → `e` is exactly {guttural} ∪ {palatal}, `ava` → `o` is
#: {guttural} ∪ {labial} — the SAME lattice join `sandhi_join` performs at a
#: word boundary, here applied word-internally. Attested and productive:
#: abhibhavati ~ abhibhoti, anavakāsa ~ anokāsa, palāyati ~ paleti.
#:
#: `ayi` → `e` is the same join before a front vowel, and it is the causative
#: absolutive that makes it productive: bhāvayitvā ~ bhāvetvā, pakappayitvā ~
#: pakappetvā, visosayitvā ~ visosetvā. Added 2026-08-02 after a dpd-db
#: integration benchmark found those pairs among the handful its own detector
#: caught and this one missed — they sat at d=1.65, which no threshold
#: reaches. Measured by the same protocol as the other six: +0.86 recall
#: points at θ=ONE_MOVE, modifying 0.6% of lemmas.
#:
#: Only these three. The long-vowel variants (āya, āva, āyi) earn nothing on
#: their own, the i-series (iya, īya) loses ground outright, and `avi` and
#: `ayu` lose too — measured, not assumed. See SPEC §6.3.
CONTRACTIONS = (("aya", "e"), ("ava", "o"), ("ayi", "e"))


def contract_word(word: str) -> str:
    """Contract `aya` → `e` and `ava` → `o` throughout a word.

    A NORMALISATION, deliberately not a distance operation. Admitting
    contraction as a 3:1 alignment transition inside `distance` was tried
    and measured: it breaks the triangle inequality, because the DP
    minimises over monotone alignments and that class is not closed under
    path composition once a transition consumes three tokens
    (d(abhibhavati, kave) exceeded the path through bhavati). The metric
    guarantee is load-bearing — BK-trees are built on it — so the
    contraction lives here instead, in the pipeline, exactly like
    `assimilate_word`:

        distance(contract_word(w1), contract_word(w2))

    Phonology first, metric second. Measured on the 5,002 pairs of DPD's
    `var_phonetic`, the full pipeline lifts agreement with DPD at
    θ=ONE_MOVE from 63.6% to 78.2%, for +2.8% candidate volume (agreement,
    not accuracy: DPD's rules compute that field).
    """
    word = normalize(word)
    if _c is not None:
        return _c.contract_word(word)
    for source, target in CONTRACTIONS:
        word = word.replace(source, target)
    return word


# --- Vowel sandhi: the lattice join, made executable -----------------------

_VOWEL_TEXT = frozenset(p.grapheme for p in VOWELS)


def _vowel_by_places(places: frozenset, long: bool) -> Optional[str]:
    """The inventory vowel with exactly those places and that length."""
    for p in VOWELS:
        if p.places == places and p.long == long:
            return p.grapheme
    return None


def sandhi_join(left: str, right: str) -> str:
    """Join two words, resolving vowel sandhi at the boundary.

    The mechanism is the JOIN of the place lattice (SPEC §3): the resulting
    vowel is the one occupying the union of both vowels' places.

    - a/ā + i/ī → e   ({G} ∪ {P} = {G,P} = e):   upa+ikkhā → upekkhā
    - a/ā + u/ū → o   ({G} ∪ {L} = {G,L} = o):   mahā+udadhi → mahodadhi
    - a/ā + e   → e,  a/ā + o → o   (the union already is the compound):
      ca+eva → ceva
    - same places → the long one:                 tatra+ayaṃ → tatrāyaṃ

    Empirical restriction: it only fires when the FIRST vowel is a/ā (the
    guṇa pattern). i+a, u+a and so on proceed by glide formation
    (aggi+agāraṃ → aggyagāraṃ) or elision — those are not the join, and are
    left untouched here. If no resulting vowel exists in the inventory, the
    words are concatenated unchanged.
    """
    t1, t2 = tokenize(left), tokenize(right)
    if not t1 or not t2:
        return normalize(left + right)
    v1, v2 = t1[-1], t2[0]
    if v1 not in _VOWEL_TEXT or v2 not in _VOWEL_TEXT:
        return "".join(t1 + t2)

    p1, p2 = phoneme(v1), phoneme(v2)
    if p1.places == p2.places:
        result = _vowel_by_places(p1.places, long=True)
    elif v1 in ("a", "ā"):
        union = p1.places | p2.places
        # e and o are long in the inventory; the join always lands long.
        result = _vowel_by_places(union, long=True)
    else:
        result = None

    if result is None:
        return "".join(t1 + t2)
    return "".join(t1[:-1] + [result] + t2[1:])
